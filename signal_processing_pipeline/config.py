"""
全局配置文件 - Signal Processing Pipeline for DUO-GAIT

包含采样率、窗口、步态检测参数
"""

import os

import numpy as np

# ============================================================
# 采样率与时间窗口配置
# ============================================================

# DUO-GAIT IMU 原始采样率（Hz）
DUO_GAIT_SAMPLE_RATE = 128

# 心率采样率（Hz）
HEART_RATE_SAMPLE_RATE = 1

# 分析窗口配置
WINDOW_LENGTH_SEC = 30          # 滑动窗口大小（秒）
SLIDING_WINDOW_STRIDE_SEC = 30  # 滑动步长（秒），非重叠设置为等于 WINDOW_LENGTH_SEC


# ============================================================
# 步频检测参数
# ============================================================

# 峰值检测最小间距（秒）
# 原值 0.06 (对应最大 ~16.7 Hz) 导致误检过多
# 改为 0.4s (对应最大 2.5 Hz)，更符合步态周期
MIN_PEAK_DISTANCE_SEC = 0.4

# 峰值高度阈值倍数（相对于信号标准差）
# 原值 1.0 太灵敏，导致检测噪声波动
# 改为 2.0-2.5 以减少误检，保留真实脚步
PEAK_HEIGHT_MULTIPLIER = 2.5

# 步频范围（Hz）
# 原值 0.5-3.0 过宽且上限过高
# 改为 0.8-2.5，符合老年人和健康人的实际步频范围
STEP_FREQUENCY_MIN_HZ = 0.5
STEP_FREQUENCY_MAX_HZ = 2.5

# ============================================================
# 步幅范围（米）
# ============================================================

STEP_LENGTH_MIN_M = 0.2
STEP_LENGTH_MAX_M = 1.5

# 步长估计输出缩放（默认 1.0）：与 LLM / fuzzy 规则量纲一致，按老年人干预场景标定；若实验需临时缩放可设环境变量。
STRIDE_LEN_OUTPUT_SCALE = float(os.environ.get("ELDER_REHAB_STRIDE_SCALE", "1.0"))

# 指标兜底：默认 False = 验证优先（不可靠时输出 null，无 FFT/无 1.5Hz 默认/无变异 clip 掩盖）。
# 设环境变量 ELDER_REHAB_METRIC_FALLBACKS=1 可恢复旧行为（生产或对比实验）。
METRIC_ALLOW_DEFAULT_FALLBACKS = os.environ.get("ELDER_REHAB_METRIC_FALLBACKS", "").lower() in (
    "1",
    "true",
    "yes",
)

# ============================================================
# 步态变异性参数
# ============================================================

# ISI 变异系数异常阈值（%）
ISI_CV_ANOMALY_THRESHOLD = 40.0

# ISI 标准差异常阈值（ms）
ISI_STD_ANOMALY_THRESHOLD = 80.0

# ============================================================
# 心率参数（bpm）
# ============================================================

HR_MIN_BPM = 30
